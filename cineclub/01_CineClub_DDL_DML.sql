-- ---------------------------------------------------------------------
-- 1.5 ALQUILER: cabecera de la transacción de renta
--     total_alquiler y total_recargos son totales controlados que
--     mantiene el trigger TR_SincronizarTotalesAlquiler (desnormalización
--     controlada exigida por el enunciado; nunca se digitan a mano).
-- ---------------------------------------------------------------------
CREATE TABLE alquiler (
    id_alquiler     INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_cliente      INTEGER       NOT NULL,
    id_empleado     INTEGER       NOT NULL,
    fecha_prestamo  DATE          NOT NULL DEFAULT CURRENT_DATE,
    fecha_limite    DATE          NOT NULL,
    total_alquiler  NUMERIC(12,2) NOT NULL DEFAULT 0,
    total_recargos  NUMERIC(12,2) NOT NULL DEFAULT 0,
    estado          VARCHAR(8)    NOT NULL DEFAULT 'Abierto',
    CONSTRAINT pk_alquiler           PRIMARY KEY (id_alquiler),
    CONSTRAINT fk_alquiler_cliente   FOREIGN KEY (id_cliente)
        REFERENCES cliente (id_cliente)   ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT fk_alquiler_empleado  FOREIGN KEY (id_empleado)
        REFERENCES empleado (id_empleado) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_alquiler_fechas    CHECK (fecha_limite > fecha_prestamo),
    CONSTRAINT ck_alquiler_totales   CHECK (total_alquiler >= 0 AND total_recargos >= 0),
    CONSTRAINT ck_alquiler_estado    CHECK (estado IN ('Abierto','Cerrado'))
);

-- ---------------------------------------------------------------------
-- 1.6 DETALLE_ALQUILER: copias específicas prestadas y su devolución
