-- ---------------------------------------------------------------------
-- 3.1 V_CatalogoDisponible
--     Copias físicas en estado 'Disponible' agrupadas por película y formato.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW V_CatalogoDisponible AS
SELECT p.id_pelicula,
       p.titulo,
       p.genero,
       p.clasificacion_edad,
       c.formato,
       COUNT(*)            AS copias_disponibles,
       p.tarifa_base_dia
  FROM pelicula p
  JOIN copia    c ON c.id_pelicula = p.id_pelicula
 WHERE c.estado = 'Disponible'
 GROUP BY p.id_pelicula, p.titulo, p.genero, p.clasificacion_edad, c.formato, p.tarifa_base_dia;

COMMENT ON VIEW V_CatalogoDisponible IS
 'Cantidad de copias disponibles por película y formato (DVD, Blu-ray, 4K).';

-- ---------------------------------------------------------------------
-- 3.2 V_AlquileresEnMora
--     Alquileres 'Abierto' con fecha_limite vencida; una fila por copia
--     aún no devuelta, con días de mora y recargo estimado a la fecha.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW V_AlquileresEnMora AS
SELECT a.id_alquiler,
       cl.id_cliente,
       cl.documento_identidad,
       cl.nombres || ' ' || cl.apellidos           AS cliente,
       cl.telefono,
       cl.email,
       p.titulo,
       c.codigo_barras,
       c.formato,
       a.fecha_prestamo,
       a.fecha_limite,
       (CURRENT_DATE - a.fecha_limite)              AS dias_mora,
       ROUND((CURRENT_DATE - a.fecha_limite) * p.tarifa_base_dia * 1.5, 2) AS recargo_estimado,
       ((CURRENT_DATE - a.fecha_limite) > 3)        AS cliente_bloqueado
  FROM alquiler         a
  JOIN cliente          cl ON cl.id_cliente = a.id_cliente
  JOIN detalle_alquiler d  ON d.id_alquiler = a.id_alquiler
  JOIN copia            c  ON c.id_copia    = d.id_copia
  JOIN pelicula         p  ON p.id_pelicula = c.id_pelicula
 WHERE a.estado = 'Abierto'
   AND a.fecha_limite < CURRENT_DATE
   AND d.fecha_devolucion_real IS NULL;

COMMENT ON VIEW V_AlquileresEnMora IS
 'Copias de alquileres abiertos vencidos, con datos de contacto y días de mora.';

-- ---------------------------------------------------------------------
-- 3.3 V_ReporteRecaudacionMensual
--     Tarifas base facturadas (por mes del préstamo) frente a multas
--     recaudadas (por mes de la devolución real), agrupadas por año y mes.
-- ---------------------------------------------------------------------
CREATE OR REPLACE VIEW V_ReporteRecaudacionMensual AS
WITH movimientos AS (
    SELECT DATE_TRUNC('month', a.fecha_prestamo)::date AS mes_inicio,
           d.precio_alquiler AS tarifa,
           0::numeric        AS mora,
           a.id_alquiler     AS id_alquiler
      FROM alquiler a JOIN detalle_alquiler d ON d.id_alquiler = a.id_alquiler
    UNION ALL
    SELECT DATE_TRUNC('month', d.fecha_devolucion_real)::date,
           0::numeric,
           d.recargo_mora,
           NULL
      FROM detalle_alquiler d
     WHERE d.fecha_devolucion_real IS NOT NULL
       AND d.recargo_mora > 0
)
SELECT EXTRACT(YEAR  FROM mes_inicio)::int        AS anio,
       EXTRACT(MONTH FROM mes_inicio)::int        AS mes,
       TO_CHAR(mes_inicio, 'YYYY-MM')             AS periodo,
       COUNT(DISTINCT id_alquiler)                AS cantidad_alquileres,
       SUM(tarifa)                                AS total_tarifas_base,
       SUM(mora)                                  AS total_multas_mora,
       SUM(tarifa) + SUM(mora)                    AS total_recaudado,
       ROUND(100.0 * SUM(mora) / NULLIF(SUM(tarifa) + SUM(mora), 0), 2) AS pct_multas
  FROM movimientos
 GROUP BY mes_inicio
 ORDER BY anio, mes;

COMMENT ON VIEW V_ReporteRecaudacionMensual IS
 'Facturación mensual: tarifas base vs. multas por mora, por año y mes.';


