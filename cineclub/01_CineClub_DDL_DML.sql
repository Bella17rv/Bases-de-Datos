/* =====================================================================
   2. TRIGGERS (lógica activa)
   Reglas de negocio:
     * precio_alquiler   = tarifa_base_dia x (fecha_limite - fecha_prestamo)
     * dias_retraso      = max(0, fecha_devolucion_real - fecha_limite)
     * recargo_mora      = dias_retraso x tarifa_base_dia x 1.5
                           (cada día de mora cuesta 150 % de la tarifa diaria)
     * Un cliente queda bloqueado si está 'Suspendida' o si tiene copias
       sin devolver con más de 3 días de atraso.
   ===================================================================== */

-- ---------------------------------------------------------------------
-- 2.1 TR_ValidarClienteHabilitado  (BEFORE INSERT en ALQUILER)  [OBLIGATORIO]
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_validar_cliente_habilitado()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_estado     cliente.estado_membresia%TYPE;
    v_nombre     TEXT;
    v_pendientes INTEGER;
    v_max_mora   INTEGER;
BEGIN
    -- FOR SHARE: evita que otra transacción cambie la membresía mientras se valida
    SELECT estado_membresia, nombres || ' ' || apellidos
      INTO v_estado, v_nombre
      FROM cliente
     WHERE id_cliente = NEW.id_cliente
       FOR SHARE;

    IF NOT FOUND THEN
        RAISE EXCEPTION 'El cliente con id % no existe.', NEW.id_cliente
              USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF v_estado = 'Suspendida' THEN
        RAISE EXCEPTION 'Alquiler rechazado: el cliente % (id %) tiene la membresía SUSPENDIDA.',
                        v_nombre, NEW.id_cliente
              USING ERRCODE = 'check_violation',
                    HINT    = 'Reactive la membresía antes de registrar nuevos alquileres.';
    END IF;

    SELECT COUNT(*), MAX(CURRENT_DATE - a.fecha_limite)
      INTO v_pendientes, v_max_mora
      FROM alquiler a
      JOIN detalle_alquiler d ON d.id_alquiler = a.id_alquiler
     WHERE a.id_cliente = NEW.id_cliente
       AND d.fecha_devolucion_real IS NULL
       AND CURRENT_DATE - a.fecha_limite > 3;

    IF v_pendientes > 0 THEN
        RAISE EXCEPTION 'Alquiler rechazado: el cliente % (id %) tiene % copia(s) sin devolver con hasta % días de atraso (máximo permitido: 3).',
                        v_nombre, NEW.id_cliente, v_pendientes, v_max_mora
              USING ERRCODE = 'check_violation',
                    HINT    = 'El cliente debe devolver las copias vencidas antes de un nuevo préstamo.';
    END IF;

    -- Un alquiler nuevo siempre nace abierto y con totales en cero
    NEW.estado         := 'Abierto';
    NEW.total_alquiler := 0;
    NEW.total_recargos := 0;
    RETURN NEW;
END;
$$;

CREATE TRIGGER TR_ValidarClienteHabilitado
BEFORE INSERT ON alquiler
FOR EACH ROW EXECUTE FUNCTION fn_validar_cliente_habilitado();


-- ---------------------------------------------------------------------
-- 2.2 TR_PrepararDetalleAlquiler  (BEFORE INSERT en DETALLE_ALQUILER) [auxiliar]
--     Calcula el precio pactado y garantiza valores iniciales coherentes.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_preparar_detalle_alquiler()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_alq    alquiler%ROWTYPE;
    v_tarifa pelicula.tarifa_base_dia%TYPE;
BEGIN
    SELECT * INTO v_alq FROM alquiler WHERE id_alquiler = NEW.id_alquiler;
    IF NOT FOUND THEN
        RAISE EXCEPTION 'El alquiler % no existe.', NEW.id_alquiler
              USING ERRCODE = 'foreign_key_violation';
    END IF;

    IF v_alq.estado = 'Cerrado' THEN
        RAISE EXCEPTION 'No se pueden agregar copias al alquiler % porque ya está CERRADO.', NEW.id_alquiler
              USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.fecha_devolucion_real IS NOT NULL THEN
        RAISE EXCEPTION 'La devolución no se registra al insertar: use UPDATE sobre fecha_devolucion_real.'
              USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.precio_alquiler IS NULL THEN
        SELECT p.tarifa_base_dia INTO v_tarifa
          FROM copia c JOIN pelicula p ON p.id_pelicula = c.id_pelicula
         WHERE c.id_copia = NEW.id_copia;
        NEW.precio_alquiler := v_tarifa * (v_alq.fecha_limite - v_alq.fecha_prestamo);
    END IF;

    NEW.dias_retraso := 0;
    NEW.recargo_mora := 0;
    RETURN NEW;
END;
$$;

CREATE TRIGGER TR_PrepararDetalleAlquiler
BEFORE INSERT ON detalle_alquiler
FOR EACH ROW EXECUTE FUNCTION fn_preparar_detalle_alquiler();


-- ---------------------------------------------------------------------
-- 2.3 TR_ActualizarEstadoCopiaAlquiler  (AFTER INSERT en DETALLE_ALQUILER) [OBLIGATORIO]
--     El UPDATE ... WHERE estado = 'Disponible' es atómico: toma un bloqueo
--     de fila sobre la copia, por lo que dos transacciones concurrentes
--     nunca pueden alquilar la misma copia (la segunda espera y luego falla).
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_actualizar_estado_copia_alquiler()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_estado copia.estado%TYPE;
    v_codigo copia.codigo_barras%TYPE;
    v_titulo pelicula.titulo%TYPE;
BEGIN
    UPDATE copia
       SET estado = 'Alquilada'
     WHERE id_copia = NEW.id_copia
       AND estado   = 'Disponible';

    IF NOT FOUND THEN
        SELECT c.estado, c.codigo_barras, p.titulo
          INTO v_estado, v_codigo, v_titulo
          FROM copia c JOIN pelicula p ON p.id_pelicula = c.id_pelicula
         WHERE c.id_copia = NEW.id_copia;

        RAISE EXCEPTION 'Copia NO disponible: la copia % (código %, "%") está en estado ''%''. Se cancela la transacción.',
                        NEW.id_copia, v_codigo, v_titulo, v_estado
              USING ERRCODE = 'check_violation',
                    HINT    = 'Consulte V_CatalogoDisponible para elegir otra copia.';
    END IF;

    RETURN NULL;   -- el valor de retorno de un AFTER ... FOR EACH ROW se ignora
END;
$$;

CREATE TRIGGER TR_ActualizarEstadoCopiaAlquiler
AFTER INSERT ON detalle_alquiler
FOR EACH ROW EXECUTE FUNCTION fn_actualizar_estado_copia_alquiler();


-- ---------------------------------------------------------------------
-- 2.4 TR_CalcularMoraYDisponibilidad  (BEFORE UPDATE en DETALLE_ALQUILER) [OBLIGATORIO]
--     Se dispara al registrar (o corregir) fecha_devolucion_real.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_calcular_mora_y_disponibilidad()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_fecha_prestamo alquiler.fecha_prestamo%TYPE;
    v_fecha_limite   alquiler.fecha_limite%TYPE;
    v_tarifa         pelicula.tarifa_base_dia%TYPE;
BEGIN
    -- No se permite "deshacer" una devolución ya registrada
    IF OLD.fecha_devolucion_real IS NOT NULL AND NEW.fecha_devolucion_real IS NULL THEN
        RAISE EXCEPTION 'No se puede anular la devolución del detalle %: la copia ya fue reintegrada al inventario.',
                        OLD.id_detalle
              USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.fecha_devolucion_real IS NULL THEN
        RETURN NEW;   -- actualización que no toca la devolución
    END IF;

    SELECT a.fecha_prestamo, a.fecha_limite, p.tarifa_base_dia
      INTO v_fecha_prestamo, v_fecha_limite, v_tarifa
      FROM alquiler a
      JOIN copia    c ON c.id_copia    = NEW.id_copia
      JOIN pelicula p ON p.id_pelicula = c.id_pelicula
     WHERE a.id_alquiler = NEW.id_alquiler;

    IF NEW.fecha_devolucion_real < v_fecha_prestamo THEN
        RAISE EXCEPTION 'Fecha de devolución inválida (%): es anterior a la fecha de préstamo (%).',
                        NEW.fecha_devolucion_real, v_fecha_prestamo
              USING ERRCODE = 'check_violation';
    END IF;

    IF NEW.fecha_devolucion_real > CURRENT_DATE THEN
        RAISE EXCEPTION 'Fecha de devolución inválida (%): no puede ser futura.', NEW.fecha_devolucion_real
              USING ERRCODE = 'check_violation';
    END IF;

    -- Cálculo automático de mora (sobrescribe cualquier valor enviado a mano)
    NEW.dias_retraso := GREATEST(0, NEW.fecha_devolucion_real - v_fecha_limite);
    NEW.recargo_mora := ROUND(NEW.dias_retraso * v_tarifa * 1.5, 2);

    -- Sólo en la PRIMERA devolución la copia vuelve al inventario
    IF OLD.fecha_devolucion_real IS NULL THEN
        UPDATE copia
           SET estado = 'Disponible'
         WHERE id_copia = NEW.id_copia
           AND estado   = 'Alquilada';   -- una copia marcada 'Dañada' no se reactiva
    END IF;

    RETURN NEW;
END;
$$;

CREATE TRIGGER TR_CalcularMoraYDisponibilidad
BEFORE UPDATE ON detalle_alquiler
FOR EACH ROW EXECUTE FUNCTION fn_calcular_mora_y_disponibilidad();


-- ---------------------------------------------------------------------
-- 2.5 TR_SincronizarTotalesAlquiler (AFTER INSERT/UPDATE/DELETE en DETALLE) [auxiliar]
--     Mantiene total_alquiler, total_recargos y cierra el alquiler cuando
--     todas sus copias han sido devueltas.
-- ---------------------------------------------------------------------
CREATE OR REPLACE FUNCTION fn_sincronizar_totales_alquiler()
RETURNS TRIGGER LANGUAGE plpgsql AS $$
DECLARE
    v_id INTEGER := COALESCE(NEW.id_alquiler, OLD.id_alquiler);
BEGIN
    UPDATE alquiler a
       SET total_alquiler = t.suma_precio,
           total_recargos = t.suma_mora,
           estado = CASE WHEN t.items > 0 AND t.pendientes = 0 THEN 'Cerrado' ELSE 'Abierto' END
      FROM (SELECT COALESCE(SUM(precio_alquiler),0)                    AS suma_precio,
                   COALESCE(SUM(recargo_mora),0)                       AS suma_mora,
                   COUNT(*)                                            AS items,
                   COUNT(*) FILTER (WHERE fecha_devolucion_real IS NULL) AS pendientes
              FROM detalle_alquiler
             WHERE id_alquiler = v_id) t
     WHERE a.id_alquiler = v_id;
    RETURN NULL;
END;
$$;

CREATE TRIGGER TR_SincronizarTotalesAlquiler
AFTER INSERT OR UPDATE OR DELETE ON detalle_alquiler
FOR EACH ROW EXECUTE FUNCTION fn_sincronizar_totales_alquiler();


