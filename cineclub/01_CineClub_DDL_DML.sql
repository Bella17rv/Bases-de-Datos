-- ---------------------------------------------------------------------
-- 1.1 PELICULA: catálogo de títulos (información descriptiva y tarifa)
-- ---------------------------------------------------------------------
CREATE TABLE pelicula (
    id_pelicula        INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    titulo             VARCHAR(150)  NOT NULL,
    clasificacion_edad VARCHAR(5)    NOT NULL,
    genero             VARCHAR(40)   NOT NULL,
    anio_estreno       SMALLINT      NOT NULL,
    tarifa_base_dia    NUMERIC(10,2) NOT NULL,
    CONSTRAINT pk_pelicula           PRIMARY KEY (id_pelicula),
    CONSTRAINT uq_pelicula_titulo_anio UNIQUE (titulo, anio_estreno),
    CONSTRAINT ck_pelicula_clasif    CHECK (clasificacion_edad IN ('G','PG','PG-13','R','NC-17')),
    CONSTRAINT ck_pelicula_anio      CHECK (anio_estreno BETWEEN 1888 AND 2100),
    CONSTRAINT ck_pelicula_tarifa    CHECK (tarifa_base_dia > 0)
);
COMMENT ON TABLE  pelicula IS 'Catálogo de películas. Una película puede tener muchas copias físicas.';
COMMENT ON COLUMN pelicula.anio_estreno    IS 'Año de estreno (año_estreno en el enunciado; se evita la ñ en el identificador).';
COMMENT ON COLUMN pelicula.tarifa_base_dia IS 'Valor en pesos (COP) por día de alquiler.';

-- ---------------------------------------------------------------------
-- 1.2 COPIA: existencias físicas individuales de cada película
-- ---------------------------------------------------------------------
CREATE TABLE copia (
    id_copia       INTEGER      GENERATED BY DEFAULT AS IDENTITY,
    id_pelicula    INTEGER      NOT NULL,
    codigo_barras  VARCHAR(20)  NOT NULL,
    formato        VARCHAR(10)  NOT NULL,
    estado         VARCHAR(12)  NOT NULL DEFAULT 'Disponible',
    CONSTRAINT pk_copia           PRIMARY KEY (id_copia),
    CONSTRAINT uq_copia_codigo    UNIQUE (codigo_barras),
    CONSTRAINT fk_copia_pelicula  FOREIGN KEY (id_pelicula)
        REFERENCES pelicula (id_pelicula) ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT ck_copia_formato   CHECK (formato IN ('DVD','Blu-ray','4K')),
    CONSTRAINT ck_copia_estado    CHECK (estado  IN ('Disponible','Alquilada','Dañada'))
);
COMMENT ON TABLE copia IS 'Cada fila es un disco físico con su propio código de barras.';

-- ---------------------------------------------------------------------
-- 1.3 CLIENTE: socios del videoclub
