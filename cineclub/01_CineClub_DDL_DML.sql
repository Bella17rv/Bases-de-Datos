-- ---------------------------------------------------------------------
CREATE TABLE detalle_alquiler (
    id_detalle             INTEGER       GENERATED BY DEFAULT AS IDENTITY,
    id_alquiler            INTEGER       NOT NULL,
    id_copia               INTEGER       NOT NULL,
    precio_alquiler        NUMERIC(10,2) NOT NULL,
    fecha_devolucion_real  DATE,
    dias_retraso           INTEGER       NOT NULL DEFAULT 0,
    recargo_mora           NUMERIC(10,2) NOT NULL DEFAULT 0,
    CONSTRAINT pk_detalle_alquiler   PRIMARY KEY (id_detalle),
    CONSTRAINT fk_detalle_alquiler   FOREIGN KEY (id_alquiler)
        REFERENCES alquiler (id_alquiler) ON UPDATE CASCADE ON DELETE CASCADE,
    CONSTRAINT fk_detalle_copia      FOREIGN KEY (id_copia)
        REFERENCES copia (id_copia)       ON UPDATE CASCADE ON DELETE RESTRICT,
    CONSTRAINT uq_detalle_alq_copia  UNIQUE (id_alquiler, id_copia),
    CONSTRAINT ck_detalle_precio     CHECK (precio_alquiler >= 0),
    CONSTRAINT ck_detalle_retraso    CHECK (dias_retraso >= 0),
    CONSTRAINT ck_detalle_recargo    CHECK (recargo_mora >= 0)
);
-- precio_alquiler lo calcula el trigger si no se envía; el NOT NULL se valida después del BEFORE.

